#!/usr/bin/env python3
"""Quarantine manifest REVISE files only with an explicit, hash-verified apply flag.

Default behavior is a dry run. Source files are never deleted. The manifest must
have been generated by research/dataset_manifest.py and paths must remain under
the repository data directory.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def quarantine(manifest_path: Path, quarantine_dir: Path, apply: bool = False) -> dict:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema") != "btc_dataset_manifest_v2":
        raise ValueError("unsupported_manifest_schema")
    data_dir = Path(manifest["data_dir"]).resolve()
    quarantine_dir = quarantine_dir.resolve()
    if quarantine_dir == data_dir or data_dir in quarantine_dir.parents:
        raise ValueError("quarantine_directory_must_be_outside_data_tree")
    actions = []
    for entry in manifest.get("files", []):
        if entry.get("integrity_status") != "REVISE":
            continue
        source = (ROOT / entry["relative_path"]).resolve()
        if data_dir not in source.parents:
            raise ValueError("manifest_source_path_outside_data_tree")
        if not source.is_file():
            actions.append({"source": entry["relative_path"], "status": "MISSING"})
            continue
        actual_hash = sha256_file(source)
        if actual_hash != entry.get("sha256"):
            actions.append({"source": entry["relative_path"], "status": "HASH_MISMATCH_NO_ACTION"})
            continue
        target = quarantine_dir / source.relative_to(data_dir)
        if target.exists():
            actions.append({"source": entry["relative_path"], "target": str(target), "status": "TARGET_EXISTS_NO_ACTION"})
            continue
        if not apply:
            actions.append({"source": entry["relative_path"], "target": str(target), "sha256": actual_hash, "status": "DRY_RUN"})
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(source), str(target))
        if sha256_file(target) != actual_hash:
            raise RuntimeError(f"post_move_hash_mismatch:{entry['relative_path']}")
        actions.append({"source": entry["relative_path"], "target": str(target), "sha256": actual_hash, "status": "MOVED"})
    return {
        "schema": "btc_quarantine_run_v1",
        "mode": "APPLY" if apply else "DRY_RUN",
        "manifest": str(manifest_path),
        "actions_count": len(actions),
        "moved_count": sum(item["status"] == "MOVED" for item in actions),
        "actions": actions,
        "warning": "Moving data files changes repository paths. Review dry-run output and back up data before --apply.",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default="data/processed/btc_multisession_manifest_v2.json")
    parser.add_argument("--quarantine-dir", default="data_quarantine")
    parser.add_argument("--apply", action="store_true", help="Actually move REVISE files; default is dry-run.")
    args = parser.parse_args()
    manifest_path = Path(args.manifest).resolve()
    result = quarantine(manifest_path, Path(args.quarantine_dir), apply=args.apply)
    print(json.dumps({k: v for k, v in result.items() if k != "actions"}, indent=2))
    for item in result["actions"]:
        print(item["status"], item["source"], "->", item.get("target", ""))


if __name__ == "__main__":
    main()
